/*
 * PORT extension (#47): dynamic biquad pools. Every DSP core has one pool of biquads that its
 * channels share; the lengths per channel are stored in the EEPROM of the MCU and the DSP
 * program is generated from them while it is written to the DSP's EEPROM.
 * License: MIT
 */
#ifndef DSP_POOL_H_
#define DSP_POOL_H_
#include <stdint.h>

/* biquads of a channel and its virtual biquad offset (band b = offset + b), like
 * data_flow_ch_bq_limits / data_flow_ch_bq_offsets, with the pool lengths applied */
uint8_t flow_bq_limit(uint8_t ch);
uint16_t flow_bq_offset(uint8_t ch);

/* boot image of a DSP EEPROM, generated byte by byte (core 1..3) */
struct dsp_img {
	const uint8_t *img;      /* base image (after the size word) */
	const uint8_t *t;        /* pool table, NULL: copy the base image */
	uint16_t size, base_size, pos;
	uint8_t q0;              /* first pool index of the core */
	uint16_t nwords, sum;
	/* word generator */
	uint16_t piece, k, patch;
	uint16_t seg_lines, slot0, src;
	uint8_t seg_n, eo;
	uint16_t eb, x1, x2;
	uint16_t dst[8];
	uint16_t off[8];
	uint8_t w[7], wi, done;
};
void dsp_img_open(struct dsp_img *g, uint8_t core, const uint8_t *code);
uint8_t dsp_img_next(struct dsp_img *g);

/* pool lengths in pool order (dsp_pool_channel); cores without a pool (V30-96LN) report 0 */
uint8_t dsp_pool_cores(void);
uint8_t dsp_pool_channels(uint8_t core, uint8_t *first);   /* -> count, first pool index */
uint8_t dsp_pool_channel(uint8_t q);
uint8_t dsp_pool_len(uint8_t q);
uint8_t dsp_pool_min(uint8_t q);
uint16_t dsp_pool_size(uint8_t core);
uint8_t dsp_pool_check(const uint8_t *len);                 /* lengths of all pool channels */
void dsp_pool_store(const uint8_t *len);
uint8_t dsp_pool_set(uint8_t core, const uint8_t *len);      /* lengths of one core, moves the presets */
void dsp_pool_load(void);

#endif

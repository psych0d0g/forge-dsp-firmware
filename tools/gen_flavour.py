#!/usr/bin/env python3
"""Generate the per-flavour C configuration from the BASCOM sources.

  gen_flavour.py FIRMWARE_DIR OUT_DIR [--check]

For every devices/<PCB>/<model>/<flow>/main.bas:
  OUT_DIR/<PCB>-<model>/flavour.h        all numeric/string `const` of the resolved
                                          build as BAS_<NAME>, pin aliases as PIN_<NAME>_*
  OUT_DIR/<PCB>-<model>/flavour_pins.c   pin setup of pins.bas in source order
  OUT_DIR/<PCB>-<model>/flavour_eram.h   EEPROM layout: every `dim ... as ERAM` in declaration
                                          order from address 0 (verified against the release
                                          HEX with tools/verify_eram.py)
--check: fail if the generated files differ from what is on disk.
"""

import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bas_resolve import Resolver, strip_comment  # noqa: E402

HEADER = ("/* GENERATED by tools/gen_flavour.py from the Forge DSP BASCOM firmware 1.11.6000\n"
          " * (bitbucket.org/forge-dsp/firmware, Mark Duprau, CC BY-NC-SA 4.0). Do not edit. */\n")

PINCTRL = re.compile(r"^port([a-f])_pin([0-7])ctrl\s*=\s*(.+)$", re.I)
DDR = re.compile(r"^ddr([a-f])\s*=\s*(.+)$", re.I)
ALIAS = re.compile(r"^([A-Za-z_]\w*)\s+alias\s+(port|pin)([a-f])\.([0-7])$", re.I)
SETRESET = re.compile(r"^(set|reset)\s+([A-Za-z_]\w*)$", re.I)
CONST = re.compile(r"^const\s+", re.I)


def c_string(v):
    v = re.sub(r"\{(\d{3})\}", lambda m: "\\%03o" % int(m.group(1)), v)
    return '"' + v.replace('"', '\\"') + '"'


def flavour_id(main):
    parts = os.path.normpath(main).split(os.sep)
    return f"{parts[-4]}-{parts[-3]}"


ERAM = re.compile(r"^dim\s+(\w+)\s*(?:\(([^)]*)\))?\s+as\s+eram\s+(\w+)(?:\s*\*\s*(\w+))?"
                  r"(?:\s+at\s+(\w+)\s*\(([^)]*)\)\s+overlay)?\s*$", re.I)
ERAM_SIZE = {"byte": 1, "word": 2, "integer": 2, "dword": 4, "long": 4, "single": 4, "double": 8}


def eram_layout(r):
    """[(name, address, count, element_size, type)] in BASCOM allocation order."""
    out, addr, by_name = [], 0, {}
    for line in r.flat:
        code = strip_comment(re.sub(r"\s+'[^']*$", "", line))
        m = ERAM.match(code)
        if not m:
            continue
        name, dim, typ, strl, at_name, at_idx = m.groups()
        n = r.value(dim) if dim else 1
        t = typ.lower()
        size = r.value(strl) + 1 if t == "string" else ERAM_SIZE[t]
        if at_name:  # overlay: no allocation
            _, base, _, esize, _ = by_name[at_name.lower()]
            a = base + (r.value(at_idx) - 1) * esize
        else:
            a = addr
            addr += n * size
        e = (name, a, n, size, t)
        by_name[name.lower()] = e
        out.append(e)
    return out, addr


def generate(main):
    r = Resolver(main).run()
    fid = flavour_id(main)
    consts = r.consts
    h = [HEADER, f"#ifndef FLAVOUR_H_\n#define FLAVOUR_H_\n",
         f'#define FLAVOUR_ID "{fid}"',
         f"#define FLAVOUR_MODEL {c_string(str(consts.get('model_id', '')))}",
         f"#define FLAVOUR_BOARD {c_string(str(consts.get('board_version', '')))}", ""]
    h.append("/* BASCOM consts (resolved build, source order) */")
    skipped = []
    for name, v in consts.items():
        n = "BAS_" + name.upper()
        if isinstance(v, bool):
            h.append(f"#define {n} {int(v)}")
        elif isinstance(v, int):
            h.append(f"#define {n} {v}" if v >= 0 else f"#define {n} ({v})")
        elif isinstance(v, float):
            h.append(f"#define {n} {v!r}f")
        elif isinstance(v, str) and not re.search(r"[=<>]", v):
            h.append(f"#define {n} {c_string(v)}")
        else:
            skipped.append(f"{name} = {v}")
    if skipped:
        h.append("/* not translated: */")
        h += [f"/*   {s.replace('*/', '* /')} */" for s in skipped]

    # pins.bas of the device
    pin_lines = []
    for line in r.flat:
        m = re.search(r"'(devices/[^']*/pins\.bas):(\d+)$", line)
        if m:
            code = strip_comment(line[:m.start()])
            if code:
                pin_lines.append((code, f"{m.group(1)}:{m.group(2)}"))
    aliases = {}
    body = []
    for code, src in pin_lines:
        if CONST.match(code):
            continue
        m = PINCTRL.match(code)
        if m:
            val = r.value(m.group(3))
            body.append(f"\tPORT{m.group(1).upper()}.PIN{m.group(2)}CTRL = 0x{val:02X};  /* {src} */")
            continue
        m = DDR.match(code)
        if m:
            val = r.value(m.group(2))
            body.append(f"\tPORT{m.group(1).upper()}.DIR = 0x{val:02X};  /* {src} */")
            continue
        m = ALIAS.match(code)
        if m:
            aliases[m.group(1).lower()] = (m.group(3).upper(), int(m.group(4)),
                                           m.group(2).lower() == "port", src)
            continue
        m = SETRESET.match(code)
        if m:
            name = m.group(2).lower()
            if name not in aliases:
                raise SystemExit(f"{fid}: {src}: unknown alias {name}")
            port, bit, _, _ = aliases[name]
            op = "OUTSET" if m.group(1).lower() == "set" else "OUTCLR"
            body.append(f"\tPORT{port}.{op} = PIN{bit}_bm;  /* {code} ({src}) */")
            continue
        raise SystemExit(f"{fid}: {src}: unhandled pins.bas statement: {code}")

    h.append("\n/* pin aliases of pins.bas: PORT = output (BASCOM PORTx.n), PIN = input (PINx.n) */")
    for name, (port, bit, out, src) in aliases.items():
        n = "PIN_" + name.upper()
        h.append(f"#define {n}_PORT PORT{port}  /* {src} */")
        h.append(f"#define {n}_bp {bit}")
        h.append(f"#define {n}_bm (1 << {bit})")
        h.append(f"#define {n}_IS_OUTPUT {int(out)}")
    h.append("\nvoid flavour_pins_init(void);\n\n#endif")
    c = [HEADER, "#include <avr/io.h>", '#include "flavour.h"', "",
         "/* pins.bas in source order: PINnCTRL, DIR (OUT still 0), initial levels */",
         "void flavour_pins_init(void)", "{"] + body + ["}"]
    layout, total = eram_layout(r)
    e = [HEADER, "#ifndef FLAVOUR_ERAM_H_\n#define FLAVOUR_ERAM_H_\n",
         "/* internal EEPROM (BASCOM ERAM), 0-based addresses; mapped at MAPPED_EEPROM_START.",
         " * _COUNT = elements (BASCOM index 1.._COUNT), _SIZE = bytes per element. */",
         f"#define ERAM_TOTAL_SIZE {total}", ""]
    for name, a, n, size, t in layout:
        N = "ERAM_" + name.upper()
        e.append(f"#define {N} {a}  /* {t}{' x' + str(n) if n > 1 else ''} */")
        e.append(f"#define {N}_COUNT {n}")
        e.append(f"#define {N}_SIZE {size}")
    e.append("\n#endif")
    return fid, "\n".join(h) + "\n", "\n".join(c) + "\n", "\n".join(e) + "\n", layout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("firmware")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    mains = sorted(glob.glob(os.path.join(a.firmware, "devices", "*", "*", "*", "main.bas")))
    if not mains:
        raise SystemExit("no devices/*/*/*/main.bas found")
    bad = 0
    for main in mains:
        fid, h, c, e, _ = generate(main)
        d = os.path.join(a.out, fid)
        for name, text in (("flavour.h", h), ("flavour_pins.c", c), ("flavour_eram.h", e)):
            p = os.path.join(d, name)
            if a.check:
                old = open(p).read() if os.path.exists(p) else None
                if old != text:
                    print(f"out of date: {p}")
                    bad += 1
            else:
                os.makedirs(d, exist_ok=True)
                with open(p, "w") as f:
                    f.write(text)
        print(fid)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()

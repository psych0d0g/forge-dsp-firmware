#!/usr/bin/env python3
"""Optimized DSP programs as build input (issue #47).

For each flavour with the 96ELN program layout, takes dsp_1_code and dsp_2_code from its
flavour_data.h, applies tas3108_opt (program 1: interleave, program 2: forward), checks the
result against the rules (tas3108_asm.check) and against the original in the simulator
(tas3108_sim.compare, bit-identical outputs and memory), and writes src/flavours/<f>/dsp_opt.h with
dsp_1_code_opt / dsp_2_code_opt in the format of dsp_N_code (size word, then the image).
The build uses them with -DFORGE_DSP_OPT=1.

    dsp_opt_gen.py [--check]     --check: only verify that the headers are up to date
License: MIT
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dsp_image  # noqa: E402
import dsp_pool  # noqa: E402
import tas3108_asm as asm  # noqa: E402
import tas3108_dis as dis  # noqa: E402
import tas3108_opt as opt  # noqa: E402
import tas3108_sim as sim  # noqa: E402

ROOT = os.path.join(HERE, "..")
FLAVOURS = ["V30-96ELN", "V40-96ELN", "V40-96ELN-3", "V40-CORED8", "V41-96ELN-3", "V41-CORED8"]  # not V30-96LN


def optimize(img, n):
    blocks, rest = dsp_image.parse(img)
    words = dis.program(blocks)
    new = opt.interleave_delays(words) if n == 1 else opt.fill_waits_forward(words, dsp_image.regmap(blocks))
    errors = asm.check(new)
    if errors:
        raise SystemExit(f"program {n}: rule check failed: {errors[:3]}")
    out = dsp_image.build(asm.replace_program(blocks, new), rest)
    diff = sim.compare(img, out, frames=64)
    if diff:
        raise SystemExit(f"program {n}: not equal to the original: {diff}")
    return out, asm.cycles(words), asm.cycles(new)


def table(name, img, what="optimized program", size_word=True):
    data = (bytes([len(img) & 0xFF, len(img) >> 8]) if size_word else b"") + img
    lines = [f"/* {name}: {what}, {len(img)} bytes (tools/dsp_opt_gen.py) */",
             f"BAS_DATA_TABLE({name}, {len(data)}) = {{"]
    for i in range(0, len(data), 16):
        lines.append("\t" + " ".join(f"0x{b:02X}," for b in data[i:i + 16]))
    lines.append("};")
    return "\n".join(lines)


def header(flavour):
    path = os.path.join(ROOT, "src", "flavours", flavour, "flavour_data.h")
    parts = ["/* generated by tools/dsp_opt_gen.py from flavour_data.h, do not edit (issue #47) */",
             "#ifndef DSP_OPT_H_", "#define DSP_OPT_H_"]
    report, imgs = [], {}
    for n in (1, 2):
        out, before, after = optimize(dsp_image.extract(path, n), n)
        imgs[n] = out
        parts.append(table(f"dsp_{n}_code_opt", out))
        report.append(f"program {n}: {before} -> {after} cycles")
    # dynamic biquad pools (#47): tables of the generator in src/dsp_pool.c
    progs, cores = dsp_pool.programs(path, imgs)
    parts.append("#define DSP_POOL 1")
    for n, p in progs.items():
        parts.append(table(f"dsp_{n}_pool", p.c_table(), "pool tables (tools/dsp_pool.py)", False))
    chans, first = [], []
    for k in sorted(cores):
        first.append(len(chans))
        chans += [ch for ch, _, _ in cores[k]]
    first.append(len(chans))
    parts.append(f"#define DSP_POOL_CORES {len(cores)}\n#define DSP_POOL_CHANNELS {len(chans)}\n"
                 f"/* channels of the pools in pool order, core 1 first; core k owns [first[k-1], first[k]) */\n"
                 f"static const uint8_t dsp_pool_chan[DSP_POOL_CHANNELS] = {{{', '.join(map(str, chans))}}};\n"
                 f"static const uint8_t dsp_pool_core_first[DSP_POOL_CORES + 1] = {{{', '.join(map(str, first))}}};")
    report.append("pools " + ", ".join(f"core {k}: {sum(n for _, _, n in cores[k])}" for k in sorted(cores)))
    parts.append("#endif")
    return "\n".join(parts) + "\n", report


def main(argv):
    check = "--check" in argv
    stale = 0
    for f in FLAVOURS:
        text, report = header(f)
        dst = os.path.join(ROOT, "src", "flavours", f, "dsp_opt.h")
        old = open(dst).read() if os.path.exists(dst) else None
        if check:
            if old != text:
                print(f"{f}: dsp_opt.h out of date")
                stale += 1
            continue
        if old != text:
            open(dst, "w").write(text)
        print(f"{f}: " + ", ".join(report))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
